part of 'telegram_tools.dart';

/// Data access is independent of whether a call asks for approval.
enum ToolAccess {
  read('Read', 'Reads or inspects data without changing user data.'),
  modify('Modify', 'Creates, sends, saves or changes data or device state.'),
  destructive(
    'Destructive',
    'Deletes, removes, replaces or destroys data; always asks first.',
  );

  const ToolAccess(this.label, this.description);
  final String label;
  final String description;
}

class ToolPolicy {
  const ToolPolicy(this.access, {this.needsTelegram = false});
  final ToolAccess access;
  final bool needsTelegram;
}

/// Prerequisites only; the person's enable switch and read-only mode are
/// separate so Settings can explain every reason a tool is unavailable.
List<String> toolPrerequisiteProblems(
  TelegramTool tool,
  AppSettings settings, {
  required bool telegram,
  required Set<String> connected,
  bool modelSeesImages = true,
  bool decisionsReady = true,
}) {
  final problems = <String>[];
  if (tool.category == ToolCategory.decisions && !decisionsReady) {
    problems.add(
      'Add a TypeSafe Jev key and turn Decisions on in AI & models.',
    );
  }
  if (tool.needsTelegram && !telegram)
    problems.add('Connect Telegram in Apps & web.');
  if (isAppTool(tool.name)) {
    if (!settings.hasComposioKey)
      problems.add('Add a Composio key in Apps & web.');
    final app = appToolkitOf(tool.name);
    if (app != null && !connected.contains(app))
      problems.add('Connect ${appLabel(app)} in Apps & web.');
  }
  if (creativeToolNeeds(tool, settings) case final reason?)
    problems.add(reason);
  if (cloudToolNeeds(tool, settings) case final reason?) problems.add(reason);
  if (!deviceToolReady(tool)) problems.add('Requires the Android app.');
  if ((tool.category == ToolCategory.code ||
          tool.name.startsWith('browser_')) &&
      !(Platform.isAndroid || Platform.isIOS || Platform.isMacOS)) {
    problems.add('Requires Android, iOS or macOS.');
  }
  if (const {
        'web_screenshot',
        'web_inspect',
        'web_run_async_js',
      }.contains(tool.name) &&
      !InAppEngine.supported) {
    problems.add('Requires Android or iOS.');
  }
  if (tool.name == 'web_search' && !settings.hasExaKey)
    problems.add('Add an Exa key in Apps & web.');
  if (tool.name == 'generate_addis_voice' && !settings.hasAddisKey)
    problems.add('Add an Addis AI key in AI & models.');
  if (!settings.mediaEnabled &&
      const {'generate_image', 'view_image'}.contains(tool.name)) {
    problems.add('Images are off in AI & models → Images & video.');
  }
  if (tool.name == 'generate_video') {
    if (!settings.videoEnabled)
      problems.add('Video is off in AI & models → Images & video.');
    if (settings.videoModel.isEmpty)
      problems.add('Pick a video model in AI & models → Images & video.');
  }
  if (!settings.voiceEnabled &&
      const {
        'generate_audio',
        'generate_addis_voice',
        'generate_music',
        'generate_sound_effect',
      }.contains(tool.name)) {
    problems.add('Voice is off in AI & models.');
  }
  if (tool.name == 'view_image' && !modelSeesImages)
    problems.add('Choose a chat model with image input in AI & models.');
  final model = switch (tool.name) {
    'generate_image' => settings.imageModel,
    'generate_video' when settings.videoModel.isNotEmpty => settings.videoModel,
    'generate_audio' when settings.voiceEngine == VoiceEngine.elevenLabs =>
      'elevenlabs:${settings.elevenModel}',
    'generate_audio' when settings.voiceEngine != VoiceEngine.addis =>
      settings.speechModel,
    _ => null,
  };
  if (tool.name == 'generate_audio' &&
      settings.voiceEngine == VoiceEngine.addis &&
      !settings.hasAddisKey) {
    problems.add('Add an Addis AI key in AI & models.');
  }
  if (model != null) {
    final provider = canonicalModelId(model).split(':').first;
    final configured = switch (provider) {
      'gateway' => settings.hasVercelKey,
      'google' => settings.hasGeminiKey,
      'openrouter' => settings.hasOpenRouterKey,
      'lmstudio' => settings.hasLmStudio,
      'elevenlabs' => settings.hasElevenKey,
      'addis' => settings.hasAddisKey,
      _ => false,
    };
    if (!configured)
      problems.add(
        'Configure the selected ${switch (tool.name) {
          'generate_image' => 'image',
          'generate_video' => 'video',
          _ => 'speech',
        }} model in AI & models.',
      );
  }
  return problems;
}

String toolApprovalDescription(TelegramTool tool, AppSettings settings) {
  if (tool.destructive || tool.alwaysAsk)
    return 'Always asks for approval, including when other approvals are skipped.';
  if (!tool.requiresApproval)
    return 'Runs without an approval prompt when enabled. Read-only mode still blocks changes.';
  final policy = switch (settings.approvalMode) {
    ApprovalMode.ask => 'Asks for approval before acting.',
    ApprovalMode.watches =>
      'Asks in chat; watch actions may run without asking.',
    ApprovalMode.never =>
      'Runs without asking, according to your approval setting.',
  };
  return '$policy${const {'bot_api', 'device_volume', 'join_chat', 'share_folder'}.contains(tool.name) ? ' Read-only variants do not need approval.' : ''}';
}

